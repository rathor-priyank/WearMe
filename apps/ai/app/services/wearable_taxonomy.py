# Legacy & synonym aliases mapped to canonical WearableSubcategory keys
CATEGORY_ALIASES: dict[str, str] = {
    "PANTS": "TROUSERS",
    "JEANS": "TROUSERS",
    "SHORTS": "TROUSERS",
    "KURTI": "ETHNIC_WEAR",
    "SALWAR_SUIT": "ETHNIC_WEAR",
    "SHOES": "SNEAKERS",
    "GLASSES": "PRESCRIPTION_GLASSES",
}


def resolve_wearable_spec(
    category: str,
    subcategory: str | None = None,
) -> WearableSpec | None:
    """
    Resolve a `(category, subcategory)` pair or single category identifier to
    its canonical `WearableSpec`. Returns `None` if unrecognized.
    """
    candidate = (subcategory or category or "").strip().upper()
    if not candidate:
        return None
    canonical = CATEGORY_ALIASES.get(candidate, candidate)
    if canonical in WEARABLE_SPECS:
        return WEARABLE_SPECS[canonical]

    # Also allow passing domain as category when subcategory is omitted
    cat_norm = (category or "").strip().upper()
    canonical_cat = CATEGORY_ALIASES.get(cat_norm, cat_norm)
    return WEARABLE_SPECS.get(canonical_cat)

